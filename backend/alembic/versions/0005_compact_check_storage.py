def _day_partition(day) -> str:
    lo = datetime(day.year, day.month, day.day, tzinfo=UTC)
    hi = lo + timedelta(days=1)
    return (
        f"CREATE TABLE IF NOT EXISTS check_results_p{lo:%Y%m%d} PARTITION OF check_results "
        f"FOR VALUES FROM ('{lo:%Y-%m-%d} 00:00:00+00') TO ('{hi:%Y-%m-%d} 00:00:00+00')"
    )


